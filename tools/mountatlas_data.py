"""Generates MountAtlas/Data.lua from Simple Armory's mounts.json.

Simple Armory (https://github.com/kevinclement/SimpleArmory, MIT License, (c) Kevin Clement)
groups every mount by expansion or theme and then by how it is obtained. This script keeps that
layout, maps each subcategory to one of MountAtlas' source types and writes it as Lua.

Usage (from the repository root):
    python tools/mountatlas_data.py                 # downloads the current mounts.json
    python tools/mountatlas_data.py path/to/mounts.json

Run it again after each patch and commit the new Data.lua.
"""

import datetime
import json
import os
import re
import sys
import urllib.request
from collections import Counter

SOURCE_URL = "https://raw.githubusercontent.com/kevinclement/SimpleArmory/master/static/data/mounts.json"
OUT_PATH = os.path.join(os.path.dirname(__file__), "..", "MountAtlas", "Data.lua")

# Simple Armory category name -> expansion index (EXPANSION_NAME<n> in the game).
EXPANSIONS = {
    "Classic": 0, "The Burning Crusade": 1, "Wrath of the Lich King": 2, "Cataclysm": 3,
    "Mists of Pandaria": 4, "Warlords of Draenor": 5, "Legion": 6, "Battle for Azeroth": 7,
    "Shadowlands": 8, "Dragonflight": 9, "The War Within": 10, "Midnight": 11,
}

# Whole categories whose mounts all share one source type.
CATEGORY_TYPES = {
    "PVP": "pvp",
    "World Events": "event",
    "Professions": "profession",
    "Racial": "classrace",
    "Promotion": "shop",
    "Mythic+": "dungeon",
}

# Subcategory rules, checked in order (regex on the subcategory name, case-insensitive).
SUBCAT_RULES = [
    (r"achievement|feats of strength|mage tower|challenge mode|^collect$", "achievement"),
    (r"raid drop", "raid"),
    (r"dungeon drop|timewalking", "dungeon"),
    (r"renown|reputation|paragon|netherwing|sha'tari|kurenai|mag'har|golden lotus|cloud serpent|"
     r"shado-pan|tillers|cenarion|talon's vengeance|argent tournament", "reputation"),
    (r"rare spawn|world boss|nemesis drop|prey drop|tormentors", "rare"),
    (r"vendor|dubloons|medals|mark of honor", "vendor"),
    (r"quest|campaign|callings|daily activities", "quest"),
    (r"treasure|zone drop|zone feature|^zone$|ritual sites|riddle|primal eggs|"
     r"protoform|emerald bounty", "world"),
    (r"store|trading post|promotion|collector's edition|trading card|annual subscription|"
     r"recruit-a-friend|twitch|blizzcon|hearthstone|heroes|hots|warcraft iii|diablo|"
     r"pringles|razer|steelseries|fanta|make-a-wish|wow forever|wow classic|anniversary|"
     r"azeroth choppers|player vote|bmah", "shop"),
    (r"halaa|ashran|honor|gladiator|vicious|brawler", "pvp"),
    (r"class hall|paladin|warlock|death knight|demon hunter|allied race|dracthyr|pandaren|"
     r"human|night elf|gnome|dwarf|draenei|worgen|orc|undead|tauren|troll|blood elf|goblin", "classrace"),
    (r"fishing|archaeology|engineering|tailoring|jewelcrafting|leatherworking|alchemy|blacksmith|"
     r"tinkering", "profession"),
    (r"love is in the air|brewfest|darkmoon|hallow's end|noblegarden|winter veil|lunar festival|"
     r"midsummer|pre-launch event|events", "event"),
]


def source_type(category, subcat):
    if category in CATEGORY_TYPES:
        return CATEGORY_TYPES[category]
    for pattern, kind in SUBCAT_RULES:
        if re.search(pattern, subcat, re.IGNORECASE):
            return kind
    return "other"


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def load(path):
    if path:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    with urllib.request.urlopen(SOURCE_URL) as r:
        return json.loads(r.read().decode("utf-8"))


def main():
    data = load(sys.argv[1] if len(sys.argv) > 1 else None)
    out = []
    w = out.append
    w("-- MountAtlas: mount list generated by tools/mountatlas_data.py. Do not edit by hand.")
    w("-- Source: Simple Armory (https://github.com/kevinclement/SimpleArmory), MIT License,")
    w("-- Copyright (c) Kevin Clement. Layout: group (expansion or theme) > subcategory > mounts.")
    w("-- Mount fields: id = mountID, n = English name, f = faction-only (\"A\"/\"H\"),")
    w("-- no = no longer obtainable, rs = resold on the Black Market Auction House.")
    w("")
    w("local ADDON, ns = ...")
    w("")
    w("ns.DATA_DATE = %s" % lua_string(datetime.date.today().isoformat()))
    w("")
    w("ns.DATA = {")
    types = Counter()
    others = Counter()
    kept = skipped = 0
    for cat in data:
        name = cat["name"]
        exp = EXPANSIONS.get(name)
        limited = name == "Limited Time"
        head = "    { name = %s" % lua_string(name)
        if exp is not None:
            head += ", expansion = %d" % exp
        if limited:
            head += ", limited = true"
        w(head + ", subs = {")
        for sub in cat["subcats"]:
            kind = source_type(name, sub["name"])
            items = []
            for it in sub["items"]:
                # Same rules as Simple Armory: these are never listed.
                if it.get("notReleased") or it.get("highlighted"):
                    skipped += 1
                    continue
                fields = ["id = %d" % it["ID"], "n = %s" % lua_string(it["name"])]
                if it.get("side") in ("A", "H"):
                    fields.append('f = "%s"' % it["side"])
                if it.get("notObtainable"):
                    fields.append("no = true")
                if it.get("resale"):
                    fields.append("rs = true")
                items.append("{ " + ", ".join(fields) + " }")
            if not items:
                continue
            kept += len(items)
            types[kind] += len(items)
            if kind == "other":
                others["%s > %s" % (name, sub["name"])] += len(items)
            line = "        { name = %s, type = %s" % (lua_string(sub["name"]), lua_string(kind))
            if sub.get("info"):
                line += ", info = %s" % lua_string(sub["info"].strip())
            w(line + ", mounts = {")
            for item in items:
                w("            " + item + ",")
            w("        } },")
        w("    } },")
    w("}")
    with open(OUT_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("Wrote %s: %d mounts (%d unreleased/hidden skipped)" % (os.path.normpath(OUT_PATH), kept, skipped))
    print("By type:", dict(types.most_common()))
    print("Mapped to 'other':", dict(others.most_common()))


if __name__ == "__main__":
    main()
